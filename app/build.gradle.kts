// Release signing credentials live in a git-ignored properties file
// (keystore/keystore.properties), so the repo can be published without
// shipping the signing key or its password.
val signingProps = Properties().apply {
    val propsFile = rootProject.file("keystore/keystore.properties")
    if (propsFile.exists()) {
        propsFile.inputStream().use { load(it) }
    }
}

